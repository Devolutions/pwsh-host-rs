#nullable enable

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;
using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace Devolutions.MultiPwsh.LiveContract.Generator;

[Generator]
public sealed class LiveContractGenerator : IIncrementalGenerator
{
    private const int MaximumWireBytes = 256;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<INamedTypeSymbol> declarations = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is Microsoft.CodeAnalysis.CSharp.Syntax.InterfaceDeclarationSyntax { AttributeLists.Count: > 0 },
                static (syntax, _) => (INamedTypeSymbol)syntax.SemanticModel.GetDeclaredSymbol(syntax.Node)!)
            .Where(static type => HasAttribute(type, "LiveContractAttribute") || HasAttribute(type, "LiveObjectAttribute"));

        IncrementalValueProvider<string> mode = context.AnalyzerConfigOptionsProvider
            .Select(static (options, _) => options.GlobalOptions.TryGetValue("build_property.LiveContractMode", out string? value) ? value : string.Empty);

        context.RegisterSourceOutput(declarations.Collect().Combine(mode), static (production, pair) =>
        {
            List<INamedTypeSymbol> types = pair.Left
                .GroupBy(static type => type, SymbolEqualityComparer.Default)
                .Select(static group => group.First())
                .ToList();
            List<INamedTypeSymbol> roots = types.Where(static type => HasAttribute(type, "LiveContractAttribute")).ToList();

            // A reference to the SDK attributes must not turn ordinary consumers into
            // diagnostics merely because they do not declare a generated contract.
            if (roots.Count == 0)
            {
                return;
            }

            if (roots.Count != 1)
            {
                foreach (INamedTypeSymbol root in roots)
                {
                    production.ReportDiagnostic(Diagnostic.Create(InvalidContract, GetLocation(root), root.Name,
                        "exactly one [LiveContract] root is allowed per compilation"));
                }

                return;
            }

            if (pair.Right is not ("Host" or "Payload"))
            {
                production.ReportDiagnostic(Diagnostic.Create(MissingMode, GetLocation(roots[0])));
                return;
            }

            var diagnostics = new List<Diagnostic>();
            ContractInfo? contract = Analyze(roots[0], types, diagnostics);
            foreach (Diagnostic diagnostic in diagnostics)
            {
                production.ReportDiagnostic(diagnostic);
            }

            if (contract is null)
            {
                return;
            }

            StringBuilder source = new();
            source.AppendLine("// <auto-generated/>");
            source.AppendLine("#nullable enable");
            if (!string.IsNullOrEmpty(contract.Namespace))
            {
                source.Append("namespace ").Append(contract.Namespace).AppendLine(";");
                source.AppendLine();
            }
            EmitConstants(source, contract, pair.Right);
            if (pair.Right == "Host")
            {
                EmitHost(source, contract);
            }
            else
            {
                EmitPayload(source, contract);
            }

            production.AddSource($"{contract.Root.Name}.{pair.Right}.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
        });
    }

    private static ContractInfo? Analyze(INamedTypeSymbol root, List<INamedTypeSymbol> types, List<Diagnostic> diagnostics)
    {
        bool valid = true;
        AttributeData? contractAttribute = GetAttribute(root, "LiveContractAttribute");
        if (contractAttribute is null ||
            contractAttribute.ConstructorArguments.Length != 4 ||
            contractAttribute.ConstructorArguments[0].Value is not string contractId ||
            string.IsNullOrWhiteSpace(contractId) ||
            contractAttribute.ConstructorArguments[1].Value is not int major ||
            major <= 0 ||
            contractAttribute.ConstructorArguments[2].Value is not int minor ||
            minor < 0 ||
            contractAttribute.ConstructorArguments[3].Value is not string interfaceId ||
            !Guid.TryParse(interfaceId, out Guid parsedInterfaceId) ||
            parsedInterfaceId == Guid.Empty)
        {
            diagnostics.Add(Diagnostic.Create(InvalidContract, GetLocation(root), root.Name,
                "a stable contract ID, positive major version, non-negative minor version, and non-empty interface IID are required"));
            return null;
        }

        if (root.ContainingType is not null)
        {
            diagnostics.Add(Diagnostic.Create(UnsupportedSurface, GetLocation(root), root.Name, "nested interfaces are not supported"));
            valid = false;
        }

        List<ObjectInfo> objects = new();
        var objectIds = new HashSet<ulong>();
        foreach (INamedTypeSymbol type in types.Where(static type => HasAttribute(type, "LiveObjectAttribute")))
        {
            AttributeData? objectAttribute = GetAttribute(type, "LiveObjectAttribute");
            if (type.ContainingType is not null)
            {
                diagnostics.Add(Diagnostic.Create(UnsupportedSurface, GetLocation(type), type.Name, "nested interfaces are not supported"));
                valid = false;
            }

            if (type.TypeParameters.Length != 0 ||
                objectAttribute is null ||
                objectAttribute.ConstructorArguments.Length != 1 ||
                objectAttribute.ConstructorArguments[0].Value is not ulong objectId ||
                objectId == 0 ||
                !objectIds.Add(objectId))
            {
                diagnostics.Add(Diagnostic.Create(InvalidObject, GetLocation(type), type.Name));
                valid = false;
                continue;
            }

            objects.Add(new ObjectInfo(type, objectId));
        }

        ObjectInfo? rootObject = objects.FirstOrDefault(objectInfo => SymbolEqualityComparer.Default.Equals(objectInfo.Symbol, root));
        if (rootObject is null)
        {
            diagnostics.Add(Diagnostic.Create(InvalidContract, GetLocation(root), root.Name, "the root must also declare a non-zero [LiveObject] ID"));
            return null;
        }

        var memberIds = new HashSet<uint>();
        foreach (ObjectInfo objectInfo in objects)
        {
            foreach (ISymbol member in objectInfo.Symbol.GetMembers())
            {
                if (member is IEventSymbol)
                {
                    diagnostics.Add(Diagnostic.Create(UnsupportedSurface, GetLocation(member), member.Name, "events are not supported"));
                    valid = false;
                    continue;
                }

                if (member is not IMethodSymbol && member is not IPropertySymbol)
                {
                    continue;
                }

                if (member is IMethodSymbol { MethodKind: MethodKind.PropertyGet or MethodKind.PropertySet })
                {
                    continue;
                }

                AttributeData? memberAttribute = GetAttribute(member, "LiveMemberAttribute");
                if (memberAttribute is null)
                {
                    diagnostics.Add(Diagnostic.Create(UnsupportedSurface, GetLocation(member), member.Name, "every declared method and property must have [LiveMember]"));
                    valid = false;
                    continue;
                }

                if (memberAttribute.ConstructorArguments.Length != 1 ||
                    memberAttribute.ConstructorArguments[0].Value is not uint memberId ||
                    memberId == 0 ||
                    !memberIds.Add(memberId))
                {
                    diagnostics.Add(Diagnostic.Create(InvalidMember, GetLocation(member), member.Name));
                    valid = false;
                    continue;
                }

                uint setterId = GetNamedUInt(memberAttribute, "SetterId");
                ulong resultObjectId = GetNamedULong(memberAttribute, "ResultObjectId");
                int maximumUtf8Bytes = GetNamedInt(memberAttribute, "MaximumUtf8Bytes");
                int maximumCollectionCount = GetNamedInt(memberAttribute, "MaximumCollectionCount");

                if (member is IPropertySymbol property)
                {
                    if (property.IsIndexer || property.IsStatic || property.GetMethod is null)
                    {
                        diagnostics.Add(Diagnostic.Create(UnsupportedSurface, GetLocation(member), member.Name, "indexers, static properties, and write-only properties are not supported"));
                        valid = false;
                        continue;
                    }

                    if (property.SetMethod is not null)
                    {
                        if (setterId == 0 || !memberIds.Add(setterId))
                        {
                            diagnostics.Add(Diagnostic.Create(InvalidSetter, GetLocation(member), member.Name));
                            valid = false;
                            continue;
                        }
                    }
                    else if (setterId != 0)
                    {
                        diagnostics.Add(Diagnostic.Create(UnsupportedSurface, GetLocation(member), member.Name, "a getter-only property cannot declare SetterId"));
                        valid = false;
                        continue;
                    }

                    if (IsString(property.Type))
                    {
                        if (!HasValidUtf8Cap(maximumUtf8Bytes))
                        {
                            diagnostics.Add(Diagnostic.Create(MissingStringCap, GetLocation(member), member.Name));
                            valid = false;
                            continue;
                        }

                        objectInfo.Members.Add(new MemberInfo(objectInfo, member, memberId, setterId, resultObjectId,
                            maximumUtf8Bytes, maximumCollectionCount, MemberShape.StringProperty, null));
                        continue;
                    }

                    if (property.Type.SpecialType == SpecialType.System_Int32 && property.SetMethod is null)
                    {
                        if (maximumCollectionCount <= 0)
                        {
                            diagnostics.Add(Diagnostic.Create(MissingCollectionCap, GetLocation(member), member.Name));
                            valid = false;
                            continue;
                        }

                        objectInfo.Members.Add(new MemberInfo(objectInfo, member, memberId, setterId, resultObjectId,
                            maximumUtf8Bytes, maximumCollectionCount, MemberShape.CountProperty, null));
                        continue;
                    }

                    if (TryGetReadOnlyListElement(property.Type, out INamedTypeSymbol? elementType))
                    {
                        ObjectInfo? resultObject = FindObject(objects, resultObjectId);
                        if (resultObject is null || FindObject(objects, elementType!) is null)
                        {
                            diagnostics.Add(Diagnostic.Create(MissingResultObject, GetLocation(member), member.Name));
                            valid = false;
                            continue;
                        }

                        if (property.SetMethod is not null || maximumCollectionCount <= 0)
                        {
                            diagnostics.Add(Diagnostic.Create(MissingCollectionCap, GetLocation(member), member.Name));
                            valid = false;
                            continue;
                        }

                        objectInfo.Members.Add(new MemberInfo(objectInfo, member, memberId, setterId, resultObjectId,
                            maximumUtf8Bytes, maximumCollectionCount, MemberShape.CollectionProperty, elementType));
                        continue;
                    }

                    diagnostics.Add(Diagnostic.Create(UnsupportedSurface, GetLocation(member), member.Name,
                        DescribeUnsupportedType(property.Type)));
                    valid = false;
                    continue;
                }

                IMethodSymbol method = (IMethodSymbol)member;
                if (method.IsStatic ||
                    method.MethodKind != MethodKind.Ordinary ||
                    method.TypeParameters.Length != 0 ||
                    method.Parameters.Any(static parameter => parameter.RefKind != RefKind.None || IsBanned(parameter.Type)) ||
                    IsBanned(method.ReturnType))
                {
                    diagnostics.Add(Diagnostic.Create(UnsupportedSurface, GetLocation(member), member.Name,
                        "generic, static, ref/out, delegate, dynamic, task, credential, and unsupported member forms are not supported"));
                    valid = false;
                    continue;
                }

                ObjectInfo? returnedObject = FindObject(objects, method.ReturnType);
                if (returnedObject is null || resultObjectId == 0 || resultObjectId != returnedObject.Id)
                {
                    diagnostics.Add(Diagnostic.Create(MissingResultObject, GetLocation(member), member.Name));
                    valid = false;
                    continue;
                }

                if (method.Parameters.Length == 1 && IsString(method.Parameters[0].Type))
                {
                    if (!HasValidUtf8Cap(maximumUtf8Bytes))
                    {
                        diagnostics.Add(Diagnostic.Create(MissingStringCap, GetLocation(member), member.Name));
                        valid = false;
                        continue;
                    }

                    objectInfo.Members.Add(new MemberInfo(objectInfo, member, memberId, setterId, resultObjectId,
                        maximumUtf8Bytes, maximumCollectionCount, MemberShape.StringToObjectMethod, method.ReturnType));
                    continue;
                }

                if (method.Parameters.Length == 1 && method.Parameters[0].Type.SpecialType == SpecialType.System_Int32)
                {
                    objectInfo.Members.Add(new MemberInfo(objectInfo, member, memberId, setterId, resultObjectId,
                        maximumUtf8Bytes, maximumCollectionCount, MemberShape.IntToObjectMethod, method.ReturnType));
                    continue;
                }

                diagnostics.Add(Diagnostic.Create(UnsupportedSurface, GetLocation(member), member.Name,
                    "only string-to-live-object and int-to-live-object methods are supported"));
                valid = false;
            }
        }

        if (!valid)
        {
            return null;
        }

        MemberInfo[] rootMethods = rootObject.Members.Where(static member => member.Shape == MemberShape.StringToObjectMethod).ToArray();
        MemberInfo[] rootCollections = rootObject.Members.Where(static member => member.Shape == MemberShape.CollectionProperty).ToArray();
        if (objects.Count != 3 || rootMethods.Length != 1 || rootCollections.Length != 1)
        {
            diagnostics.Add(Diagnostic.Create(RestrictedGraph, GetLocation(root), root.Name));
            return null;
        }

        MemberInfo add = rootMethods[0];
        MemberInfo collection = rootCollections[0];
        ObjectInfo collectionObject = FindObject(objects, collection.ResultObjectId)!;
        ObjectInfo childObject = FindObject(objects, collection.ResultType!)!;
        if (!SymbolEqualityComparer.Default.Equals(add.ResultType, childObject.Symbol))
        {
            diagnostics.Add(Diagnostic.Create(RestrictedGraph, GetLocation(add.Symbol), add.Symbol.Name));
            return null;
        }

        MemberInfo[] countMembers = collectionObject.Members.Where(static member => member.Shape == MemberShape.CountProperty).ToArray();
        MemberInfo[] getAtMembers = collectionObject.Members.Where(static member => member.Shape == MemberShape.IntToObjectMethod).ToArray();
        if (collectionObject.Members.Count != 2 ||
            countMembers.Length != 1 ||
            getAtMembers.Length != 1 ||
            !SymbolEqualityComparer.Default.Equals(getAtMembers[0].ResultType, childObject.Symbol) ||
            countMembers[0].MaximumCollectionCount != collection.MaximumCollectionCount)
        {
            diagnostics.Add(Diagnostic.Create(RestrictedGraph, GetLocation(collectionObject.Symbol), collectionObject.Symbol.Name));
            return null;
        }

        List<MemberInfo> childStrings = childObject.Members.Where(static member => member.Shape == MemberShape.StringProperty).ToList();
        if (childStrings.Count != childObject.Members.Count || childStrings.Count == 0)
        {
            diagnostics.Add(Diagnostic.Create(RestrictedGraph, GetLocation(childObject.Symbol), childObject.Symbol.Name));
            return null;
        }

        IParameterSymbol addParameter = ((IMethodSymbol)add.Symbol).Parameters[0];
        MemberInfo? initialProperty = childStrings.FirstOrDefault(member =>
            string.Equals(member.Symbol.Name, addParameter.Name, StringComparison.OrdinalIgnoreCase) &&
            member.SetterId != 0);
        initialProperty ??= childStrings.FirstOrDefault(static member => member.SetterId != 0);
        if (initialProperty is null)
        {
            diagnostics.Add(Diagnostic.Create(RestrictedGraph, GetLocation(add.Symbol), add.Symbol.Name));
            return null;
        }

        return new ContractInfo(
            root,
            root.ContainingNamespace.IsGlobalNamespace ? string.Empty : root.ContainingNamespace.ToDisplayString(),
            contractId,
            major,
            minor,
            parsedInterfaceId.ToString("D").ToUpperInvariant(),
            rootObject, collectionObject, childObject, add, collection, countMembers[0], getAtMembers[0], childStrings, initialProperty);
    }

    private static void EmitConstants(StringBuilder source, ContractInfo contract, string mode)
    {
        string generated = GeneratedName(contract);
        source.Append("internal static class ").Append(generated).AppendLine();
        source.AppendLine("{");
        source.Append("    internal const string ContractId = \"").Append(EscapeString(contract.ContractId)).AppendLine("\";");
        source.Append("    internal const int MajorVersion = ").Append(contract.MajorVersion.ToString(CultureInfo.InvariantCulture)).AppendLine(";");
        source.Append("    internal const int MinorVersion = ").Append(contract.MinorVersion.ToString(CultureInfo.InvariantCulture)).AppendLine(";");
        source.Append("    internal const string InterfaceId = \"").Append(EscapeString(contract.InterfaceId)).AppendLine("\";");
        source.Append("    internal const uint ContractHash = 0x").Append(ComputeHash(contract).ToString("X8", CultureInfo.InvariantCulture)).AppendLine("U;");
        source.Append("    internal const string Mode = \"").Append(mode).AppendLine("\";");
        foreach (ObjectInfo objectInfo in contract.Objects.OrderBy(static objectInfo => objectInfo.Id))
        {
            source.Append("    internal const ulong Object").Append(objectInfo.Id.ToString(CultureInfo.InvariantCulture)).Append(" = ")
                .Append(objectInfo.Id.ToString(CultureInfo.InvariantCulture)).AppendLine("UL;");
            foreach (MemberInfo member in objectInfo.Members.OrderBy(static member => member.Id))
            {
                source.Append("    internal const uint Member").Append(member.Id.ToString(CultureInfo.InvariantCulture)).Append(" = ")
                    .Append(member.Id.ToString(CultureInfo.InvariantCulture)).AppendLine("U;");
                source.Append("    internal const byte Member").Append(member.Id.ToString(CultureInfo.InvariantCulture)).Append("ResultKind = ")
                    .Append(GetResultKind(member).ToString(CultureInfo.InvariantCulture)).AppendLine(";");
                if (member.ResultObjectId != 0)
                {
                    source.Append("    internal const ulong Member").Append(member.Id.ToString(CultureInfo.InvariantCulture)).Append("ResultObjectId = ")
                        .Append(member.ResultObjectId.ToString(CultureInfo.InvariantCulture)).AppendLine("UL;");
                }
                if (member.MaximumUtf8Bytes != 0)
                {
                    source.Append("    internal const int Member").Append(member.Id.ToString(CultureInfo.InvariantCulture)).Append("MaximumUtf8Bytes = ")
                        .Append(member.MaximumUtf8Bytes.ToString(CultureInfo.InvariantCulture)).AppendLine(";");
                }
                if (member.MaximumCollectionCount != 0)
                {
                    source.Append("    internal const int Member").Append(member.Id.ToString(CultureInfo.InvariantCulture)).Append("MaximumCollectionCount = ")
                        .Append(member.MaximumCollectionCount.ToString(CultureInfo.InvariantCulture)).AppendLine(";");
                }
                if (member.SetterId != 0)
                {
                    source.Append("    internal const uint Member").Append(member.SetterId.ToString(CultureInfo.InvariantCulture)).Append(" = ")
                        .Append(member.SetterId.ToString(CultureInfo.InvariantCulture)).AppendLine("U;");
                }
            }
        }

        source.AppendLine("}");
        source.AppendLine();
    }

    private static void EmitHost(StringBuilder source, ContractInfo contract)
    {
        string prefix = TypePrefix(contract);
        string generated = GeneratedName(contract);
        string model = prefix + "HostModel";
        string childModel = TypePrefix(contract.Child.Symbol) + "HostModel";
        string adapter = prefix + "HostAdapter";
        string initialProperty = EscapeIdentifier(contract.InitialProperty.Symbol.Name);

        source.Append("internal sealed class ").Append(childModel).AppendLine();
        source.AppendLine("{");
        source.Append("    internal ").Append(childModel).AppendLine("(ulong handle) => Handle = handle;");
        source.AppendLine("    internal ulong Handle { get; }");
        foreach (MemberInfo property in contract.ChildStrings)
        {
            source.Append("    internal string ").Append(EscapeIdentifier(property.Symbol.Name)).AppendLine(" { get; set; } = string.Empty;");
        }

        source.AppendLine("}");
        source.AppendLine();
        source.Append("internal sealed class ").Append(model).AppendLine();
        source.AppendLine("{");
        source.Append("    private readonly global::System.Collections.Generic.List<").Append(childModel).AppendLine("> children = [];");
        source.Append("    private readonly global::System.Collections.Generic.Dictionary<ulong, ").Append(childModel).AppendLine("> childrenByHandle = [];");
        source.AppendLine("    internal int Count => children.Count;");
        source.Append("    internal ").Append(childModel).AppendLine(" Add(string value)");
        source.AppendLine("    {");
        source.AppendLine("        ulong handle = AllocateHandle();");
        source.Append("        var child = new ").Append(childModel).Append("(handle) { ").Append(initialProperty).AppendLine(" = value };");
        source.AppendLine("        children.Add(child);");
        source.AppendLine("        childrenByHandle.Add(handle, child);");
        source.AppendLine("        return child;");
        source.AppendLine("    }");
        source.Append("    internal bool TryGetAt(int index, out ").Append(childModel).AppendLine(" child)");
        source.AppendLine("    {");
        source.AppendLine("        if ((uint)index < (uint)children.Count)");
        source.AppendLine("        {");
        source.AppendLine("            child = children[index];");
        source.AppendLine("            return true;");
        source.AppendLine("        }");
        source.AppendLine("        child = null!;");
        source.AppendLine("        return false;");
        source.AppendLine("    }");
        source.Append("    internal bool TryGetChild(ulong handle, out ").Append(childModel).AppendLine(" child) => childrenByHandle.TryGetValue(handle, out child!);");
        source.AppendLine("    private ulong AllocateHandle()");
        source.AppendLine("    {");
        source.AppendLine("        ulong handle;");
        source.AppendLine("        do");
        source.AppendLine("        {");
        source.AppendLine("            global::System.Span<byte> bytes = stackalloc byte[sizeof(ulong)];");
        source.AppendLine("            global::System.Security.Cryptography.RandomNumberGenerator.Fill(bytes);");
        source.AppendLine("            handle = global::System.Buffers.Binary.BinaryPrimitives.ReadUInt64LittleEndian(bytes);");
        source.Append("        } while (handle == 0 || handle == ").Append(generated).Append(".Object").Append(contract.RootObject.Id.ToString(CultureInfo.InvariantCulture))
            .Append(" || handle == ").Append(generated).Append(".Object").Append(contract.CollectionObject.Id.ToString(CultureInfo.InvariantCulture)).AppendLine(" || childrenByHandle.ContainsKey(handle));");
        source.AppendLine("        return handle;");
        source.AppendLine("    }");
        source.AppendLine("}");
        source.AppendLine();
        source.Append("internal static class ").Append(adapter).AppendLine();
        source.AppendLine("{");
        source.AppendLine("    internal const int EInvalidArg = unchecked((int)0x80070057);");
        source.AppendLine("    internal const int EBounds = unchecked((int)0x8000000B);");
        source.AppendLine("    internal const int EBufferTooSmall = unchecked((int)0x8007007A);");
        source.AppendLine("    private static readonly global::System.Text.UTF8Encoding StrictUtf8 = new(false, true);");
        source.Append("    internal static int TryInvoke(").Append(model).AppendLine(" model, ulong objectId, uint memberId, byte inputTag, global::System.ReadOnlySpan<byte> input, int outputCapacity, out byte[] output, out int outputLength)");
        source.AppendLine("    {");
        source.AppendLine("        output = global::System.Array.Empty<byte>();");
        source.AppendLine("        outputLength = 0;");
        source.AppendLine("        if (outputCapacity < 0) return EInvalidArg;");

        EmitHostRootDispatch(source, contract, generated, model, childModel);
        EmitHostCollectionDispatch(source, contract, generated, model, childModel);
        EmitHostChildDispatch(source, contract, generated, childModel);

        source.AppendLine("        return EInvalidArg;");
        source.AppendLine("    }");
        source.AppendLine("    private static bool IsNull(byte tag, global::System.ReadOnlySpan<byte> input) => tag == global::Devolutions.PowerShell.Ffi.LiveObjects.PowerShellLiveObjectBrokerWire.Null && input.IsEmpty;");
        source.AppendLine("    private static bool TryReadString(byte tag, global::System.ReadOnlySpan<byte> input, int maximumBytes, out string value)");
        source.AppendLine("    {");
        source.AppendLine("        value = string.Empty;");
        source.AppendLine("        if (tag != global::Devolutions.PowerShell.Ffi.LiveObjects.PowerShellLiveObjectBrokerWire.Utf8String || input.IsEmpty || input.Length > maximumBytes) return false;");
        source.AppendLine("        try");
        source.AppendLine("        {");
        source.AppendLine("            value = StrictUtf8.GetString(input);");
        source.AppendLine("            return value.IndexOf('\\0') < 0;");
        source.AppendLine("        }");
        source.AppendLine("        catch (global::System.ArgumentException)");
        source.AppendLine("        {");
        source.AppendLine("            return false;");
        source.AppendLine("        }");
        source.AppendLine("    }");
        source.AppendLine("    private static int ReserveOutput(int length, int outputCapacity, out byte[] output, out int outputLength)");
        source.AppendLine("    {");
        source.AppendLine("        output = global::System.Array.Empty<byte>();");
        source.AppendLine("        outputLength = length;");
        source.AppendLine("        return outputCapacity < length ? EBufferTooSmall : 0;");
        source.AppendLine("    }");
        source.AppendLine("    private static int WriteOutput(byte[] value, int outputCapacity, out byte[] output, out int outputLength)");
        source.AppendLine("    {");
        source.AppendLine("        outputLength = value.Length;");
        source.AppendLine("        if (outputCapacity < value.Length)");
        source.AppendLine("        {");
        source.AppendLine("            output = global::System.Array.Empty<byte>();");
        source.AppendLine("            return EBufferTooSmall;");
        source.AppendLine("        }");
        source.AppendLine("        output = value;");
        source.AppendLine("        return 0;");
        source.AppendLine("    }");
        source.AppendLine("}");
    }

    private static void EmitHostRootDispatch(StringBuilder source, ContractInfo contract, string generated, string model, string childModel)
    {
        string addMember = "Member" + contract.Add.Id.ToString(CultureInfo.InvariantCulture);
        string collectionMember = "Member" + contract.Collection.Id.ToString(CultureInfo.InvariantCulture);
        source.Append("        if (objectId == ").Append(generated).Append(".Object").Append(contract.RootObject.Id.ToString(CultureInfo.InvariantCulture))
            .Append(" && memberId == ").Append(generated).Append('.').Append(addMember).AppendLine(")");
        source.AppendLine("        {");
        source.Append("            if (!TryReadString(inputTag, input, ").Append(contract.Add.MaximumUtf8Bytes.ToString(CultureInfo.InvariantCulture)).AppendLine(", out string value)) return EInvalidArg;");
        source.Append("            if (model.Count >= ").Append(contract.Collection.MaximumCollectionCount.ToString(CultureInfo.InvariantCulture)).AppendLine(") return EBounds;");
        source.AppendLine("            int status = ReserveOutput(global::Devolutions.PowerShell.Ffi.LiveObjects.PowerShellLiveObjectBrokerWire.HeaderSize + sizeof(ulong), outputCapacity, out output, out outputLength);");
        source.AppendLine("            if (status != 0) return status;");
        source.AppendLine("            output = global::Devolutions.PowerShell.Ffi.LiveObjects.PowerShellLiveObjectBrokerWire.EncodeObjectHandle(model.Add(value).Handle);");
        source.AppendLine("            return 0;");
        source.AppendLine("        }");
        source.Append("        if (objectId == ").Append(generated).Append(".Object").Append(contract.RootObject.Id.ToString(CultureInfo.InvariantCulture))
            .Append(" && memberId == ").Append(generated).Append('.').Append(collectionMember).AppendLine(")");
        source.AppendLine("        {");
        source.AppendLine("            if (!IsNull(inputTag, input)) return EInvalidArg;");
        source.Append("            return WriteOutput(global::Devolutions.PowerShell.Ffi.LiveObjects.PowerShellLiveObjectBrokerWire.EncodeObjectHandle(")
            .Append(generated).Append(".Object").Append(contract.CollectionObject.Id.ToString(CultureInfo.InvariantCulture))
            .AppendLine("), outputCapacity, out output, out outputLength);");
        source.AppendLine("        }");
    }

    private static void EmitHostCollectionDispatch(StringBuilder source, ContractInfo contract, string generated, string model, string childModel)
    {
        string countMember = "Member" + contract.Count.Id.ToString(CultureInfo.InvariantCulture);
        string getAtMember = "Member" + contract.GetAt.Id.ToString(CultureInfo.InvariantCulture);
        source.Append("        if (objectId == ").Append(generated).Append(".Object").Append(contract.CollectionObject.Id.ToString(CultureInfo.InvariantCulture))
            .Append(" && memberId == ").Append(generated).Append('.').Append(countMember).AppendLine(")");
        source.AppendLine("        {");
        source.AppendLine("            if (!IsNull(inputTag, input) || model.Count > " + contract.Collection.MaximumCollectionCount.ToString(CultureInfo.InvariantCulture) + ") return EInvalidArg;");
