    private static string ComputeHashInput(ContractInfo contract)
    {
        StringBuilder canonical = new();
        canonical.Append("contract|").Append(contract.ContractId).Append('|').Append(contract.MajorVersion).Append('|')
            .Append(contract.MinorVersion).Append('|').Append(contract.InterfaceId).Append(';');
        foreach (ObjectInfo objectInfo in contract.Objects.OrderBy(static objectInfo => objectInfo.Id))
        {
            canonical.Append("object|").Append(objectInfo.Id).Append(';');
            foreach (MemberInfo member in objectInfo.Members.OrderBy(static member => member.Id))
            {
                canonical.Append("member|").Append(objectInfo.Id).Append('|').Append(member.Id).Append('|')
                    .Append((int)member.Shape).Append('|').Append(GetTypeShape(member)).Append('|').Append(member.SetterId)
                    .Append('|').Append(member.ResultObjectId).Append('|').Append(member.MaximumUtf8Bytes)
                    .Append('|').Append(member.MaximumCollectionCount).Append(';');
            }
        }

        return canonical.ToString();
    }

    private static uint ComputeHash(ContractInfo contract)
    {
        uint hash = 2166136261;
        foreach (byte value in Encoding.UTF8.GetBytes(ComputeHashInput(contract)))
        {
            hash ^= value;
            hash *= 16777619;
        }

        return hash;
    }

    private static string GetTypeShape(MemberInfo member)
    {
        return member.Shape switch
        {
            MemberShape.StringProperty => member.SetterId == 0 ? "()->string" : "()->string;(string)->void",
            MemberShape.CollectionProperty => $"()->IReadOnlyList<{member.ResultType!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}>",
            MemberShape.CountProperty => "()->int",
            MemberShape.StringToObjectMethod => $"(string)->{member.ResultType!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}",
            MemberShape.IntToObjectMethod => $"(int)->{member.ResultType!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}",
            _ => throw new InvalidOperationException(),
        };
    }

    private static byte GetResultKind(MemberInfo member)
    {
        return member.Shape switch
        {
            MemberShape.StringProperty => 1,
            MemberShape.CollectionProperty => 2,
            MemberShape.StringToObjectMethod or MemberShape.IntToObjectMethod => 3,
            MemberShape.CountProperty => 4,
            _ => 0,
        };
    }

    private static bool IsString(ITypeSymbol type) => type.SpecialType == SpecialType.System_String;

    private static bool TryGetReadOnlyListElement(ITypeSymbol type, out INamedTypeSymbol? element)
    {
        element = null;
        if (type is not INamedTypeSymbol named ||
            named.Name != "IReadOnlyList" ||
            named.ContainingNamespace.ToDisplayString() != "System.Collections.Generic" ||
            named.TypeArguments.Length != 1 ||
            named.TypeArguments[0] is not INamedTypeSymbol candidate)
        {
            return false;
        }

        element = candidate;
        return true;
    }

    private static bool IsBanned(ITypeSymbol type)
    {
        if (type.TypeKind is TypeKind.Dynamic or TypeKind.Delegate ||
            type.SpecialType == SpecialType.System_Object)
        {
            return true;
        }

        string name = type.Name;
        return name.IndexOf("Task", StringComparison.OrdinalIgnoreCase) >= 0 ||
            name.IndexOf("SecureString", StringComparison.OrdinalIgnoreCase) >= 0 ||
            name.IndexOf("PSCredential", StringComparison.OrdinalIgnoreCase) >= 0 ||
            name.IndexOf("Credential", StringComparison.OrdinalIgnoreCase) >= 0;
    }

    private static string DescribeUnsupportedType(ITypeSymbol type) =>
        IsBanned(type) ? "dynamic, delegate, task, credential, and object-like types are not supported" :
        $"the type '{type.ToDisplayString()}' is not a supported live-member shape";

    private static bool HasValidUtf8Cap(int value) => value > 0 && value <= MaximumWireBytes;

    private static ObjectInfo? FindObject(IEnumerable<ObjectInfo> objects, ulong id) =>
        objects.FirstOrDefault(objectInfo => objectInfo.Id == id);

    private static ObjectInfo? FindObject(IEnumerable<ObjectInfo> objects, ITypeSymbol type) =>
        objects.FirstOrDefault(objectInfo => SymbolEqualityComparer.Default.Equals(objectInfo.Symbol, type));

    private static string GeneratedName(ContractInfo contract) => EscapeIdentifier(contract.Root.Name) + "Generated";
    private static string TypePrefix(ContractInfo contract) => TypePrefix(contract.Root);
    private static string TypePrefix(INamedTypeSymbol type) =>
        EscapeIdentifier(type.Name.Length > 1 && type.Name[0] == 'I' && char.IsUpper(type.Name[1]) ? type.Name.Substring(1) : type.Name);

    private static string EscapeIdentifier(string name) =>
        SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None || SyntaxFacts.GetContextualKeywordKind(name) != SyntaxKind.None ? "@" + name : name;

    private static string EscapeString(string value) => value.Replace("\\", "\\\\").Replace("\"", "\\\"");

    private static Location GetLocation(ISymbol symbol) => symbol.Locations.FirstOrDefault() ?? Location.None;

    private static bool HasAttribute(ISymbol symbol, string name) => GetAttribute(symbol, name) is not null;

    private static AttributeData? GetAttribute(ISymbol symbol, string name) =>
        symbol.GetAttributes().FirstOrDefault(attribute => attribute.AttributeClass?.Name == name);

    private static uint GetNamedUInt(AttributeData attribute, string name) =>
        attribute.NamedArguments.FirstOrDefault(pair => pair.Key == name).Value.Value is uint value ? value : 0;

    private static ulong GetNamedULong(AttributeData attribute, string name) =>
        attribute.NamedArguments.FirstOrDefault(pair => pair.Key == name).Value.Value is ulong value ? value : 0;

    private static int GetNamedInt(AttributeData attribute, string name) =>
        attribute.NamedArguments.FirstOrDefault(pair => pair.Key == name).Value.Value is int value ? value : 0;

